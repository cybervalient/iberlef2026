class DataAnalyzer:
    """
    Analiza los datos reales proporcionados para guiar la generación sintética.
    """

    def __init__(self, embedding_model_name: str = RESTMEX_CONFIG['EMBEDDING_MODEL']):
        logger.info(f"🔍 Cargando modelo de embeddings: {embedding_model_name}")
        self.embedding_model = SentenceTransformer(embedding_model_name)
        self.df_real = None
        self.distribution = {}

    def load_data(self, filepath: str) -> pd.DataFrame:
        """Carga y valida el CSV de datos reales."""
        logger.info(f"📂 Cargando datos desde: {filepath}")

        df = pd.read_csv(filepath)

        # Normalizar nombres de columnas
        df.columns = df.columns.str.lower().str.strip()

        # Validar columnas requeridas
        required = ['review', 'polarity']
        missing = [col for col in required if col not in df.columns]

        if missing:
            raise ValueError(f"❌ Columnas faltantes en el archivo: {missing}")

        # Limpieza básica
        df = df.dropna(subset=['review', 'polarity'])
        df['review'] = df['review'].astype(str).str.strip()
        df['polarity'] = df['polarity'].astype(int)

        # Filtrar polaridades válidas
        df = df[df['polarity'].isin(RESTMEX_CONFIG['POLARITY_CLASSES'])]

        self.df_real = df
        logger.info(f"✅ Datos cargados: {len(df)} reseñas válidas")

        return df

    def analyze_distribution(self) -> Dict[int, float]:
        """Analiza la distribución de clases de sentimiento."""
        if self.df_real is None:
            raise ValueError("Primero carga los datos con load_data()")

        counts = self.df_real['polarity'].value_counts().sort_index()
        total = len(self.df_real)

        self.distribution = {
            polarity: {
                'count': int(counts.get(polarity, 0)),
                'percentage': round(counts.get(polarity, 0) / total * 100, 2)
            }
            for polarity in RESTMEX_CONFIG['POLARITY_CLASSES']
        }

        logger.info("📊 Distribución de polaridades en datos reales:")
        for p, info in self.distribution.items():
            bar = "█" * int(info['percentage'] / 5)
            logger.info(f"  {p} ({RESTMEX_CONFIG['POLARITY_LABELS'][p]}): "
                       f"{info['count']} ({info['percentage']}%) {bar}")

        return self.distribution

    def extract_style_features(self, n_samples: int = 100) -> Dict:
        """Extrae características de estilo de las reseñas reales."""
        if self.df_real is None:
            raise ValueError("Primero carga los datos con load_data()")

        samples = self.df_real.sample(n=min(n_samples, len(self.df_real)), random_state=42)

        # Longitud promedio por polaridad
        length_stats = samples.groupby('polarity')['review'].apply(
            lambda x: {'mean': x.str.len().mean(), 'std': x.str.len().std()}
        ).to_dict()

        # Palabras más frecuentes (top 20)
        from collections import Counter
        import re

        words = []
        for text in samples['review']:
            # Tokenización simple en español
            tokens = re.findall(r'\b[a-zA-ZáéíóúñüÁÉÍÓÚÑÜ]{3,}\b', text.lower())
            words.extend(tokens)

        word_freq = Counter(words).most_common(20)

        return {
            'length_by_polarity': length_stats,
            'top_words': word_freq,
            'avg_length': samples['review'].str.len().mean()
        }

    def compute_embeddings(self, texts: List[str], batch_size: int = 32) -> np.ndarray:
        """Computa embeddings para un conjunto de textos."""
        return self.embedding_model.encode(
            texts,
            batch_size=batch_size,
            show_progress_bar=True,
            convert_to_numpy=True
        )


