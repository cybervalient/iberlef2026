class Evaluator:
    """
    Evalúa la calidad del corpus sintético usando la estrategia indirecta de REST-MEX.
    """

    def __init__(self, embedding_model: SentenceTransformer):
        self.embedding_model = embedding_model

    def compute_rp_metric(self, y_true: np.ndarray, y_pred: np.ndarray) -> float:
        """
        Calcula la métrica RP (ponderación de F1 para clases minoritarias).
        Inspirado en la descripción oficial de REST-MEX 2026.
        """
        # F1 por clase
        f1_per_class = f1_score(y_true, y_pred, average=None, labels=[1,2,3,4,5])

        # Pesos inversos a frecuencia típica en turismo (más peso a clases raras)
        # Basado en que reseñas negativas son minoritarias pero importantes
        weights = {1: 0.25, 2: 0.25, 3: 0.20, 4: 0.15, 5: 0.15}

        # F1 ponderado
        weighted_f1 = sum(
            f1_per_class[i] * weights[i+1]
            for i in range(5)
            if not np.isnan(f1_per_class[i])
        )

        return weighted_f1

    def evaluate_synthetic_corpus(
        self,
        df_synthetic: pd.DataFrame,
        df_real_val: pd.DataFrame,
        classifier_type: str = 'logistic'
    ) -> Dict:
        """
        Evalúa el corpus sintético entrenando un clasificador y probando en datos reales.
        """
        logger.info("🔬 Evaluando corpus sintético con estrategia indirecta...")

        # Preparar datos sintéticos para entrenamiento
        X_syn = self.embedding_model.encode(df_synthetic['opinion'].tolist())
        y_syn = df_synthetic['polarity'].values

        # Preparar datos reales para validación
        X_val = self.embedding_model.encode(df_real_val['review'].tolist())
        y_val = df_real_val['polarity'].values

        # Entrenar clasificador
        if classifier_type == 'logistic':
            clf = LogisticRegression(
                max_iter=1000,
                class_weight='balanced',
                random_state=42,
                C=1.0
            )
        else:
            raise ValueError(f"Clasificador no soportado: {classifier_type}")

        clf.fit(X_syn, y_syn)

        # Predecir en validación real
        y_pred = clf.predict(X_val)

        # Calcular métricas
        rp_score = self.compute_rp_metric(y_val, y_pred)
        macro_f1 = f1_score(y_val, y_pred, average='macro')

        # Reporte detallado por clase
        report = classification_report(
            y_val, y_pred,
            labels=[1,2,3,4,5],
            target_names=[RESTMEX_CONFIG['POLARITY_LABELS'][p] for p in [1,2,3,4,5]],
            output_dict=True
        )

        results = {
            'rp_score': round(rp_score, 4),
            'macro_f1': round(macro_f1, 4),
            'accuracy': round((y_pred == y_val).mean(), 4),
            'per_class_f1': {
                p: round(report[str(p)]['f1-score'], 4)
                for p in [1,2,3,4,5] if str(p) in report
            },
            'confusion_summary': {
                'total_val': len(y_val),
                'correct_predictions': int((y_pred == y_val).sum())
            }
        }

        logger.info("📊 Resultados de evaluación:")
        logger.info(f"  • RP Score (métrica oficial): {results['rp_score']:.4f}")
        logger.info(f"  • Macro F1: {results['macro_f1']:.4f}")
        logger.info(f"  • Accuracy: {results['accuracy']:.4f}")
        logger.info(f"  • F1 por clase: {results['per_class_f1']}")

        return results


