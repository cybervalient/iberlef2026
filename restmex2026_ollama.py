    def generate_review(
        self,
        polarity: int,
        aspect: Optional[str] = None,
        town: Optional[str] = None,
        temperature: float = 0.85
    ) -> Optional[Dict]:
        """Genera una sola reseña sintética con validación."""

        aspect = aspect or random.choice(self.ASPECTS)
        town = town or random.choice(self.TOWNS)

        # Obtener características de estilo si están disponibles
        try:
            style_features = self.analyzer.extract_style_features(n_samples=50)
        except:
            style_features = {'avg_length': 100, 'top_words': []}

        # Construir prompt
        prompt = self._build_prompt(polarity, aspect, town, style_features)

        # Generar con Ollama - parámetros ajustados para respuestas más largas
        text = self.ollama.generate(
            prompt, 
            temperature=temperature, 
            max_tokens=350,  # Aumentado significativamente
            min_length=20  # Mínimo aceptable
        )

        if not text:
            return None

        # Validaciones post-generación
        text = text.strip()

        # Remover posibles artefactos del prompt y respuestas del modelo
        artifacts = [
            'Reseña:', 'Assistant:', '<|eot_id|>', '<|start_header_id|>',
            'Tu reseña sobre', 'Mi reseña:', 'Opinión:', 'Comentario:',
            f'sobre {town}:', f'{town}:', 'Aquí está', 'Aquí va',
            'La reseña es:', 'Escribo:', 'Mi opinión es:',
            'Escribe tu reseña', 'aquí:', 'completa sobre'
        ]
        for artifact in artifacts:
            text = text.replace(artifact, '').strip()
        
        # Limpiar comillas al inicio y final si las hay
        text = text.strip('"\'')
        
        # Limpiar saltos de línea múltiples
        text = ' '.join(text.split())

        # Validar longitud mínima
        if len(text) < RESTMEX_CONFIG['MIN_REVIEW_LENGTH']:
            logger.warning(f"⚠️ Reseña muy corta ({len(text)} chars): '{text[:50]}...'")
            return None

        # Validar que tenga al menos 2 oraciones (heurística: buscar puntos)
        sentence_count = text.count('.') + text.count('!') + text.count('?')
        if sentence_count < 1:
            logger.warning(f"⚠️ Reseña sin estructura de oraciones: '{text[:50]}...'")
            return None

        # Validar que no sea solo una palabra
        word_count = len(text.split())
        if word_count < 10:
            logger.warning(f"⚠️ Reseña con muy pocas palabras ({word_count}): '{text}'")
            return None

        if len(text) > RESTMEX_CONFIG['MAX_REVIEW_LENGTH']:
            text = text[:RESTMEX_CONFIG['MAX_REVIEW_LENGTH']].rsplit(' ', 1)[0] + "..."

        # Validar que esté en español (heurística simple)
        spanish_indicators = ['el', 'la', 'de', 'que', 'y', 'a', 'en', 'un', 'es', 'se', 'los', 'las']
        text_lower = text.lower()
        spanish_count = sum(1 for ind in spanish_indicators if ind in text_lower)
        if spanish_count < 2:
            logger.warning(f"⚠️ Posible reseña no en español: '{text[:50]}...'")
            return None

        return {
            'opinion': text,
            'polarity': polarity,
            'source': f"Ollama-{self.ollama.model}",
            'metadata': {
                'aspect': aspect,
                'town': town,
                'length': len(text),
                'timestamp': datetime.now().isoformat()
            }
        }

    def generate_corpus(self, balance_classes: bool = True) -> pd.DataFrame:
        """
        Genera el corpus completo de 3,000 reseñas sintéticas.

        Args:
            balance_classes: Si True, genera igual número por cada polaridad
                           (recomendado para métrica RP que premia clases minoritarias)
        """
        logger.info(f"🚀 Iniciando generación de {RESTMEX_CONFIG['TARGET_REVIEWS']} reseñas...")

        self.generated_reviews = []

        if balance_classes:
            # Generación balanceada: 600 por cada polaridad (1-5)
            polarities_to_generate = []
            for p in RESTMEX_CONFIG['POLARITY_CLASSES']:
                polarities_to_generate.extend([p] * self.target_per_class)
            random.shuffle(polarities_to_generate)
        else:
            # Generación con distribución similar a datos reales
            polarities_to_generate = []
            for p, info in self.analyzer.distribution.items():
                count = int(info['percentage'] / 100 * RESTMEX_CONFIG['TARGET_REVIEWS'])
                polarities_to_generate.extend([p] * count)
            # Ajustar para llegar exactamente a 3,000
            while len(polarities_to_generate) < RESTMEX_CONFIG['TARGET_REVIEWS']:
                polarities_to_generate.append(random.choice(RESTMEX_CONFIG['POLARITY_CLASSES']))
            polarities_to_generate = polarities_to_generate[:RESTMEX_CONFIG['TARGET_REVIEWS']]
            random.shuffle(polarities_to_generate)

        # Generación con barra de progreso
        for i, polarity in enumerate(tqdm(polarities_to_generate, desc="Generando reseñas")):
            review = self.generate_review(polarity)

            if review:
                self.generated_reviews.append(review)
                self.generation_log.append({
                    'index': i,
                    'polarity': polarity,
                    'success': True,
                    'length': len(review['opinion'])
                })
            else:
                self.generation_log.append({
                    'index': i,
                    'polarity': polarity,
                    'success': False
                })

            # Pequeña pausa para no saturar Ollama
            time.sleep(0.05)

            # Guardar checkpoint cada 500 reseñas
            if (i + 1) % 500 == 0:
                self._save_checkpoint(i + 1)

        # Crear DataFrame final
        df_result = pd.DataFrame([
            {k: v for k, v in r.items() if k != 'metadata'}
            for r in self.generated_reviews
        ])

        logger.info(f"✅ Generación completada: {len(df_result)} reseñas válidas")

        return df_result

    def _save_checkpoint(self, count: int):
        """Guarda un checkpoint intermedio de la generación."""
        if not self.generated_reviews:
            return

        checkpoint = pd.DataFrame([
            {k: v for k, v in r.items() if k != 'metadata'}
            for r in self.generated_reviews
        ])
        checkpoint_file = f"checkpoint_{count}_reviews.csv"
        checkpoint.to_csv(checkpoint_file, index=False, encoding='utf-8-sig')
        logger.info(f"💾 Checkpoint guardado: {checkpoint_file} ({count} reseñas)")

    def filter_duplicates(
        self,
        df: pd.DataFrame,
        threshold: float = RESTMEX_CONFIG['SIMILARITY_THRESHOLD']
    ) -> pd.DataFrame:
        """
        Filtra reseñas duplicadas semánticamente usando embeddings.
        """
        if len(df) == 0:
            return df

        logger.info(f"🔍 Filtrando duplicados semánticos (threshold={threshold})...")

        # Calcular embeddings
        embeddings = self.analyzer.compute_embeddings(df['opinion'].tolist())

        # Algoritmo greedy para seleccionar textos diversos
        selected_indices = []

        for i in tqdm(range(len(embeddings)), desc="Filtrando diversidad"):
            is_unique = True

            for j in selected_indices:
                # Similitud coseno
                sim = np.dot(embeddings[i], embeddings[j]) / (
                    np.linalg.norm(embeddings[i]) * np.linalg.norm(embeddings[j])
                )

                if sim > threshold:
                    is_unique = False
                    break

            if is_unique:
                selected_indices.append(i)

        df_filtered = df.iloc[selected_indices].reset_index(drop=True)

        removed = len(df) - len(df_filtered)
        logger.info(f"✅ Filtrado completado: {removed} duplicados removidos, "
                   f"{len(df_filtered)} reseñas únicas")

        return df_filtered

    def optimize_for_rp_metric(
        self,
        df_candidates: pd.DataFrame,
        df_real_val: pd.DataFrame,
        target_size: int = RESTMEX_CONFIG['TARGET_REVIEWS']
    ) -> pd.DataFrame:
        """
        Selecciona el subconjunto óptimo de reseñas para maximizar la métrica RP.
        Usa un clasificador proxy para evaluar la utilidad de los datos sintéticos.
        """
        logger.info("🎯 Optimizando subconjunto para métrica RP...")

        if len(df_candidates) <= target_size:
            # Si ya tenemos 3,000 o menos, asegurar balance y retornar
            return self._balance_and_sample(df_candidates, target_size)

        # Embeddings para entrenamiento proxy
        X_syn = self.analyzer.compute_embeddings(df_candidates['opinion'].tolist())
        y_syn = df_candidates['polarity'].values

        X_val = self.analyzer.compute_embeddings(df_real_val['review'].tolist())
        y_val = df_real_val['polarity'].values

        # Estrategia: selección iterativa greedy
        # (Simplificada para tiempo de ejecución - en producción usar Active Learning)

        # Paso 1: Entrenar clasificador base con todos los candidatos
        clf_base = LogisticRegression(max_iter=1000, class_weight='balanced', random_state=42)
        clf_base.fit(X_syn, y_syn)

        # Paso 2: Evaluar importancia de instancias (simplificado: muestreo estratificado)
        # Para cada polaridad, seleccionar las reseñas más "informativas"
        # (aquí usamos diversidad como proxy de informatividad)

        selected = []

        for polarity in RESTMEX_CONFIG['POLARITY_CLASSES']:
            mask = df_candidates['polarity'] == polarity
            df_class = df_candidates[mask].copy()

            if len(df_class) == 0:
                continue

            # Calcular embeddings de esta clase
            emb_class = self.analyzer.compute_embeddings(df_class['opinion'].tolist())

            # Seleccionar centroides (k-means simplificado)
            n_select = target_size // 5  # 600 por clase

            if len(df_class) <= n_select:
                selected.extend(df_class.index.tolist())
            else:
                # Selección por diversidad: elegir puntos lejanos entre sí
                selected_idx = [0]  # Empezar con el primero

                while len(selected_idx) < n_select and len(selected_idx) < len(df_class):
                    # Encontrar el punto más lejano a los ya seleccionados
                    max_min_dist = -1
                    best_idx = None

                    for i in range(len(df_class)):
                        if i in selected_idx:
                            continue

                        # Distancia mínima a cualquier punto ya seleccionado
                        min_dist = min(
                            1 - np.dot(emb_class[i], emb_class[j]) / (
                                np.linalg.norm(emb_class[i]) * np.linalg.norm(emb_class[j]) + 1e-8
                            )
                            for j in selected_idx
                        )

                        if min_dist > max_min_dist:
                            max_min_dist = min_dist
                            best_idx = i

                    if best_idx is not None:
                        selected_idx.append(best_idx)

                # Mapear índices locales a índices originales del DataFrame
                original_indices = df_class.index[selected_idx].tolist()
                selected.extend(original_indices)

        # Crear DataFrame final
        df_optimized = df_candidates.loc[selected].reset_index(drop=True)

        # Ajustar tamaño exacto si es necesario
        if len(df_optimized) > target_size:
            df_optimized = df_optimized.sample(n=target_size, random_state=42)

        logger.info(f"✅ Optimización completada: {len(df_optimized)} reseñas seleccionadas")

        return df_optimized

    def _balance_and_sample(self, df: pd.DataFrame, target_size: int) -> pd.DataFrame:
        """Asegura balance de clases y muestrea al tamaño objetivo."""
        if len(df) <= target_size:
            return df

        # Muestreo estratificado para mantener balance
        return df.groupby('polarity', group_keys=False).apply(
            lambda x: x.sample(n=min(len(x), target_size // 5), random_state=42)
        ).reset_index(drop=True)


