def validate_submission(df: pd.DataFrame) -> List[str]:
    """
    Valida que el DataFrame cumpla con todos los requisitos de REST-MEX 2026.
    Retorna lista de errores (vacía si todo está bien).
    """
    errors = []

    # 1. Verificar columnas requeridas
    for col in RESTMEX_CONFIG['REQUIRED_COLUMNS'][:2]:  # opinion, polarity (source es opcional según ejemplo)
        if col not in df.columns:
            errors.append(f"❌ Columna faltante: '{col}'")

    if errors:
        return errors

    # 2. Verificar número de filas
    if len(df) > RESTMEX_CONFIG['TARGET_REVIEWS']:
        errors.append(f"❌ Demasiadas filas: {len(df)} > {RESTMEX_CONFIG['TARGET_REVIEWS']}")

    if len(df) == 0:
        errors.append("❌ DataFrame vacío")
        return errors

    # 3. Verificar valores nulos
    if df[['opinion', 'polarity']].isnull().any().any():
        errors.append("❌ Valores nulos en columnas requeridas")

    # 4. Verificar polaridades válidas
    invalid_polarities = df[~df['polarity'].isin(RESTMEX_CONFIG['POLARITY_CLASSES'])]
    if len(invalid_polarities) > 0:
        errors.append(f"❌ Polaridades inválidas encontradas: {invalid_polarities['polarity'].unique().tolist()}")

    # 5. Verificar longitud de reseñas
    short_reviews = df[df['opinion'].str.len() < RESTMEX_CONFIG['MIN_REVIEW_LENGTH']]
    if len(short_reviews) > 0:
        errors.append(f"⚠️ {len(short_reviews)} reseñas muy cortas (< {RESTMEX_CONFIG['MIN_REVIEW_LENGTH']} chars)")

    # 6. Verificar que sean strings
    if df['opinion'].dtype != 'object' or not all(isinstance(x, str) for x in df['opinion']):
        errors.append("❌ Columna 'opinion' debe contener strings")

    # 7. Verificar que polarity sea entero
    if not pd.api.types.is_integer_dtype(df['polarity']):
        errors.append("❌ Columna 'polarity' debe contener enteros")

    # 8. Verificar idioma (heurística: presencia de palabras en español)
    spanish_words = ['el', 'la', 'de', 'que', 'y', 'en', 'un', 'es', 'se', 'muy', 'bueno', 'mal']
    non_spanish = []

    for i, text in enumerate(df['opinion'].head(100)):  # Muestrear 100 para eficiencia
        text_lower = text.lower()
        if not any(word in text_lower for word in spanish_words):
            non_spanish.append(i)

    if len(non_spanish) > 20:  # Permitir algunos falsos positivos
        errors.append(f"⚠️ Posibles reseñas no en español: {len(non_spanish)} de 100 muestreadas")

    return errors


def export_submission(
    df: pd.DataFrame,
    output_path: str,
    team_name: str = "PhD_Team"
) -> str:
    """
    Exporta el DataFrame final en el formato exacto requerido por REST-MEX 2026.
    """
    # Crear copia para no modificar el original
    df_export = df.copy()

    # Asegurar columnas en orden correcto (según ejemplo del reto)
    columns_order = ['opinion', 'polarity']
    if 'source' in df_export.columns:
        columns_order.append('source')

    df_export = df_export[columns_order]

    # Asegurar tipos de dato correctos
    df_export['polarity'] = df_export['polarity'].astype(int)
    df_export['opinion'] = df_export['opinion'].astype(str)

    # Si falta 'source', agregar valor por defecto
    if 'source' not in df_export.columns:
        df_export['source'] = f"Ollama-llama3-{team_name}"

    # Validación final antes de exportar
    errors = validate_submission(df_export)
    if errors:
        logger.warning("⚠️ Advertencias de validación antes de exportar:")
        for error in errors:
            logger.warning(f"  {error}")

    # Exportar CSV con encoding UTF-8-SIG para compatibilidad con Excel
    df_export.to_csv(output_path, index=False, encoding='utf-8-sig')

    logger.info(f"✅ Archivo de envío generado: {output_path}")
    logger.info(f"📊 Estadísticas del envío:")
    logger.info(f"  • Total reseñas: {len(df_export)}")
    logger.info(f"  • Columnas: {df_export.columns.tolist()}")
    logger.info(f"  • Distribución de polaridades:")

    for p in RESTMEX_CONFIG['POLARITY_CLASSES']:
        count = (df_export['polarity'] == p).sum()
        logger.info(f"    {p} ({RESTMEX_CONFIG['POLARITY_LABELS'][p]}): {count}")

    return output_path


