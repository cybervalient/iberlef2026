class OllamaClient:
    """
    Cliente flexible para Ollama: soporta modo local y web API remota.
    """

    def __init__(
        self,
        model: str = "llama3",
        base_url: Optional[str] = None,
        api_key: Optional[str] = None,
        timeout: int = 90,
        max_retries: int = 15,
        mode: str = "local"
    ):
        self.model = model
        self.mode = mode
        
        # Configurar URL según el modo
        if base_url:
            self.base_url = base_url
        elif mode == "web":
            # Para modo web, usar un servidor remoto de Ollama si está configurado
            self.base_url = os.getenv("OLLAMA_API_URL", "http://localhost:11434")
        else:
            self.base_url = os.getenv("OLLAMA_API_URL", "http://localhost:11434")
        
        self.api_key = api_key or os.getenv("OLLAMA_API_KEY")
        self.timeout = timeout
        self.max_retries = max_retries
        self.session = requests.Session()

        if self.api_key:
            self.session.headers.update({"Authorization": f"Bearer {self.api_key}"})

        logger.info(f"🦙 OllamaClient inicializado: model={model}, url={self.base_url}, mode={mode}")

    def generate(
        self,
        prompt: str,
        temperature: float = 0.5,
        max_tokens: int = 150,
        top_p: float = 0.9,
        min_length: int = 10
    ) -> Optional[str]:
        """
        Genera texto usando Ollama con reintentos automáticos.
        """
        # Construir la URL correcta según el endpoint
        generate_url = f"{self.base_url}/api/generate"
        
        for attempt in range(self.max_retries):
            try:
                payload = {
                    "model": self.model,
                    "prompt": prompt,
                    "stream": False,
                    "options": {
                        "temperature": temperature,
                        "top_p": top_p,
                        "num_predict": max_tokens,
                        "repeat_penalty": 1.1,  # Reduce repetición
                        "stop": []  # No detener prematuramente
                    }
                }
                
                response = self.session.post(
                    generate_url,
                    json=payload,
                    timeout=self.timeout
                )

                if response.status_code == 200:
                    result = response.json()
                    text = result.get('response', '').strip()

                    # Validación básica de calidad
                    if text and len(text) >= min_length:
                        return text
                    else:
                        logger.warning(f"⚠️ Respuesta muy corta ({len(text)} chars): '{text[:50]}...'")
                        # Si es muy corto, no reintentar inmediatamente, continuar al siguiente intento
                else:
                    logger.error(f"❌ Error HTTP {response.status_code}: {response.text[:200]}")

            except requests.exceptions.ConnectionError:
                logger.error(f"❌ ConnectionError (intento {attempt + 1}/{self.max_retries})")
            except requests.exceptions.Timeout:
                logger.error(f"❌ Timeout (intento {attempt + 1}/{self.max_retries})")
            except Exception as e:
                logger.error(f"❌ Error inesperado (intento {attempt + 1}): {e}")

            # Backoff exponencial entre reintentos
            if attempt < self.max_retries - 1:
                wait_time = min(2 * (2 ** attempt), 16)  # Máximo 16 segundos
                logger.info(f"⏳ Esperando {wait_time}s antes de reintentar...")
                time.sleep(wait_time)
        
        logger.error(f"❌ Falló después de {self.max_retries} intentos")
        return None
    
    def parse_json(self, raw: str) -> Optional[dict]:
        raw = raw.strip()
        raw = re.sub(r"^```(?:json)?\s*", "", raw)
        raw = re.sub(r"```\s*$", "", raw).strip()
        m   = re.search(r"\{[\s\S]*\}", raw)
        if m:
            raw = m.group(0)
        try:
            return json.loads(raw)
        except json.JSONDecodeError:
            return None
    
    def complete(self, system: str, user: str) -> Optional[str]:
        """
        Completa un chat usando el formato de mensajes de Ollama.
        """
        chat_url = f"{self.base_url}/api/chat"
        
        headers = {"Content-Type": "application/json"}
        if self.api_key:
            headers["Authorization"] = f"Bearer {self.api_key}"
        
        payload = {
            "model": self.model, 
            "stream": False,
            "messages": [
                {"role": "system", "content": system},
                {"role": "user", "content": user},
            ],
            "options": {"temperature": 0.7, "num_predict": 600},
        }
        
        try:
            r = self.session.post(chat_url, headers=headers, json=payload, timeout=self.timeout)
            r.raise_for_status()
            return r.json()["message"]["content"]
        except requests.ConnectionError:
            logger.error(f"❌ [Ollama] Cannot connect to {chat_url}")
        except requests.HTTPError as e:
            logger.error(f"❌ [Ollama {e.response.status_code}] {e.response.text[:150]}")
        except (KeyError, ValueError) as e:
            logger.error(f"❌ [Ollama parse] {e}")
        return None


    def test_connection(self) -> bool:
        """Prueba rápida de conectividad con Ollama."""
        try:
            # Usar endpoint de tags para verificar conexión (más confiable)
            tags_url = f"{self.base_url}/api/tags"
            response = self.session.get(tags_url, timeout=5)
            
            if response.status_code == 200:
                models = response.json().get('models', [])
                model_names = [m.get('name', '') for m in models]
                
                # Verificar que el modelo especificado existe
                if any(self.model in name for name in model_names):
                    logger.info(f"✅ Conexión a Ollama verificada exitosamente")
                    logger.info(f"✅ Modelo '{self.model}' encontrado")
                    return True
                else:
                    logger.warning(f"⚠️ Modelo '{self.model}' no encontrado")
                    logger.info(f"📋 Modelos disponibles: {', '.join(model_names[:5])}")
                    # Aún así retornar True si la conexión funciona
                    return True
            else:
                logger.error(f"❌ Error HTTP {response.status_code}")
                return False
                
        except Exception as e:
            logger.error(f"❌ Falló la prueba de conexión: {e}")
            return False

    def close(self):
        self.session.close()

    def __enter__(self):
        return self

    def __exit__(self, *args):
        self.close()





